"""Export the actual preprocessed Iris training data for later Evidently analyses.

The source must be the saved X_train.pkl generated by src/data_processing.py;
never substitute live predictions or a newly sampled dataset for this reference.
"""
import argparse
from pathlib import Path

import joblib
import pandas as pd

FEATURE_NAMES = [
    "SepalLengthCm",
    "SepalWidthCm",
    "PetalLengthCm",
    "PetalWidthCm",
]
PROJECT_ROOT = Path(__file__).resolve().parents[1]


def export_reference(source, destination):
    reference = joblib.load(source)
    if not isinstance(reference, pd.DataFrame):
        raise TypeError("Expected a pandas DataFrame saved as X_train.pkl")
    missing = set(FEATURE_NAMES).difference(reference.columns)
    if missing:
        raise ValueError("Training reference is missing features: " + ", ".join(sorted(missing)))

    reference = reference.loc[:, FEATURE_NAMES]
    if reference.empty:
        raise ValueError("Training reference cannot be empty")
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    reference.to_csv(destination, index=False)
    return len(reference)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        type=Path,
        default=PROJECT_ROOT / "artifacts" / "processed" / "X_train.pkl",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=PROJECT_ROOT / "data" / "reference_iris.csv",
    )
    args = parser.parse_args()
    count = export_reference(args.source, args.output)
    print(f"Exported {count} reference observations to {args.output}")


if __name__ == "__main__":
    main()
